    static String render(UiMergeGen g) {
        StringBuilder sb = new StringBuilder();
        sb.append("# UI merge: GadScape's edits of vanilla interfaces and clientscripts on build 241\n\n");
        sb.append("Generated by `UiMergeMain gen` (package `com.gadscape.cacheconv.uimerge`) from BASE (openrs2 2746), USER (GadScape's 211 cache) and\n");
        sb.append("VAN211, using the decisions in `UiMergeSpecs` (interfaces) and `ScriptRecipes` (scripts). Do not edit the data files by hand:\n");
        sb.append("change the specs and regenerate; `UiMergeMain check` fails when the stored data no longer matches a regeneration.\n\n");
        sb.append("## How it works\n\n");
        sb.append("- **What the user changed** is VAN211 -> USER. Each of the 14 interfaces and 31 scripts gets one decision:\n");
        sb.append("  - **merged**: the edit is re-applied onto BASE's version. Interfaces: field by field (`IfMerge`), on the BASE component the\n");
        sb.append("    211 -> 241 remap names (server docs table checked against BASE's gamevals names, spell-obj anchors for 218, content alignment,\n");
        sb.append("    and hand overrides where the table is wrong); a field BASE changed too goes to USER for content and to BASE for layout (logged).\n");
        sb.append("    Components the user added are appended after BASE's last one. Scripts: an anchored recipe inserts GadScape's instructions into\n");
        sb.append("    BASE's body (jumps and switches keep their targets; BASE's signature is kept).\n");
        sb.append("  - **user**: BASE never changed the id since 211, so USER's version is taken (converted to 241).\n");
        sb.append("  - **base**: BASE's version is kept; the reason says why nothing (or not everything) of the user's edit is needed.\n");
        sb.append("- **Data**: `interfaces/ID.if` (component bytes in hex + the USER-sourced references), `scripts/ID.cs2` (text assembly; `u` marks\n");
        sb.append("  GadScape's lines, `@kind` their id operands), `manifest.tsv` (decision + SHA-256 of the BASE group the merge was made against).\n");
        sb.append("- **Build** (`UiMergeStep`, step `ui-merge`): refuses an entry whose BASE group changed, maps GadScape's references through the\n");
        sb.append("  id map (custom scripts, sprites, vars, configs and interfaces relocated by earlier steps), writes the groups. BASE's own code is\n");
        sb.append("  never remapped.\n");
        sb.append("- **component-remap.tsv**: 211 -> 241 component ids for every vanilla interface the server references (plus the docs table's),\n");
        sb.append("  keyed by the USER (GadScape 211) numbering the server uses; ui-convert reads it in place of the docs table.\n\n");
        sb.append("## Summary\n\n| kind | id | decision | what |\n|---|---|---|---|\n");
        for (String m : g.manifest) {
            String[] f = m.split("\t", -1);
            String note = f[5].length() > 140 ? f[5].substring(0, 137) + "..." : f[5];
            sb.append("| ").append(f[0]).append(" | ").append(f[1]).append(" | ").append(f[2]).append(" | ").append(note.replace("|", "/")).append(" |\n");
        }
        sb.append("\n## Open issues (not re-applied, or needing work elsewhere)\n\n");
        for (String o : OPEN) sb.append("- ").append(o).append('\n');
        if (!g.problems.isEmpty()) {
            sb.append("\nGenerator problems:\n");
            for (String p : g.problems) sb.append("- ").append(p).append('\n');
        }
        sb.append("\n## Interfaces\n").append(g.notesIf);
        sb.append("\n## Clientscripts\n").append(g.notesCs);
        return sb.toString();
    }

