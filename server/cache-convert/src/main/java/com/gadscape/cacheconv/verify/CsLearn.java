package com.gadscape.cacheconv.verify;

import com.gadscape.cacheconv.convert.Cs2;
import com.gadscape.cacheconv.core.JagCache;
import com.gadscape.cacheconv.core.Options;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Derives the build-241 command stack table ({@code verify/cs2-241-stack.tsv}) from a stock 241 cache (dev tool; the
 * table is checked in as data, so builds do not run this).
 * <ol>
 *   <li>Seed: the interpreter's core instructions ({@link CsTable#core()}) plus the 211-era RuneStar table
 *       ({@code ui/cs2-commands-211.tsv} and {@code -extra.tsv}).</li>
 *   <li>Learn: every opcode the stock scripts use that the seed lacks gets the effect (pops/pushes per stack) under
 *       which the scripts using it have the fewest stack violations ({@link CsStack}'s rules; stock scripts have none).
 *       Candidate pops are bounded by the depths seen before the opcode.</li>
 *   <li>Re-check: opcodes that keep appearing in statements with violations are re-learned the same way; a new effect
 *       is kept only if it lowers the violation count of the scripts that use the opcode.</li>
 * </ol>
 * Usage: {@code dev/run.sh verify.CsLearn [--base DIR] [--seed=a.tsv,b.tsv] [--table-out=FILE] [--report=FILE]}.
 * The result is deterministic (ascending ids, fixed candidate order).
 */
public final class CsLearn {
    private CsLearn() {}

    public static void main(String[] a) throws Exception {
        Options o = Options.parse(a, 0);
        Path module = Path.of(o.get("module", "server/cache-convert"));
        String seed = o.get("seed", module.resolve("src/main/resources/ui/cs2-commands-211.tsv") + "," + module.resolve("src/main/resources/ui/cs2-commands-211-extra.tsv"));
        Path out = Path.of(o.get("table-out", module.resolve("src/main/resources/verify/cs2-241-stack.tsv").toString()));
        Path manual = Path.of(o.get("manual", module.resolve("src/main/resources/verify/cs2-241-manual.tsv").toString()));
        Path report = o.get("report", null) == null ? null : Path.of(o.get("report", null));
        try (JagCache base = JagCache.open("BASE", o.base)) {
            CsWorld w = new CsWorld(base);
            CsTable t = new CsTable(CsTable.core());
            List<String> seedFiles = new ArrayList<>();
            if (Files.isRegularFile(manual)) {
                for (CsTable.Effect e : CsTable.parse(Files.readAllLines(manual)).all().values()) if (!t.has(e.op())) t.put(e);
                seedFiles.add(manual.getFileName().toString());
            }
            for (String f : seed.split(",")) {
                if (f.isBlank()) continue;
                Path p = Path.of(f);
                String src = p.getFileName().toString().contains("extra") ? "211-extra" : "211";
                for (CsTable.Effect e : CsTable.parseRuneStar(Files.readAllLines(p), src)) if (!t.has(e.op())) t.put(e);
                seedFiles.add(p.getFileName().toString());
            }
            Learner L = new Learner(w, t);
            List<String> log = L.run();
            List<String> header = new ArrayList<>();
            header.add("# Build-241 clientscript command stack effects (int i / object s / long l, bottom to top), for verify.CsStack.");
            header.add("# Generated by verify.CsLearn from the stock 241 cache (" + base.dir.getFileName() + "), seeded with " + String.join(", ", seedFiles) + ".");
            header.add("# source: core = interpreter instruction; 211 / 211-extra = RuneStar 211-era table, consistent with every stock 241 script;");
            header.add("#         learned = not in the seed, learned from the stock scripts; relearned = the seed's effect did not fit 241;");
            header.add("#         manual = hand-checked (cs2-241-manual.tsv).");
            header.add("# 'special' rows are handled by CsStack itself (operand- or constant-dependent effects); listed for reference.");
            header.add("# stock scripts: " + L.summary());
            Files.createDirectories(out.toAbsolutePath().getParent());
            Files.write(out, L.table.format(header), StandardCharsets.UTF_8);
            System.out.println("wrote " + out);
            if (report != null) { Files.createDirectories(report.toAbsolutePath().getParent()); Files.write(report, log, StandardCharsets.UTF_8); }
        }
    }

    /** The learning loop over one script set. */
    public static final class Learner {
        final CsWorld w;
        final CsTable table;
        /** op -> scripts using it (ascending). */
        final TreeMap<Integer, List<Integer>> users = new TreeMap<>();
        final TreeMap<Integer, Integer> freq = new TreeMap<>();
        TreeMap<Integer, CsStack.Result> last;
        static final int MAX_SCRIPTS = 300;

        public Learner(CsWorld w, CsTable table) {
            this.w = w; this.table = table;
            for (var e : w.scripts.entrySet()) {
                TreeSet<Integer> ops = new TreeSet<>();
                for (Cs2.Ins in : e.getValue().code) { ops.add(in.op); freq.merge(in.op, 1, Integer::sum); }
                for (int op : ops) users.computeIfAbsent(op, k -> new ArrayList<>()).add(e.getKey());
            }
        }

        static boolean special(int op) { return CsStack.isSpecial(op); }

        long violations(Map<Integer, CsStack.Result> res) {
            long n = 0;
            for (CsStack.Result r : res.values()) n += r.violations().size();
            return n;
        }

        /** Violations weighted by how many stack values they are off (lets a pair of wrong ops improve one at a time). */
        long weight(Map<Integer, CsStack.Result> res) {
            long n = 0;
            for (CsStack.Result r : res.values()) for (CsStack.Problem p : r.violations()) n += 1 + Math.max(0, p.size());
            return n;
        }

        long visited(Map<Integer, CsStack.Result> res) {
            long n = 0;
            for (CsStack.Result r : res.values()) n += r.visited;
            return n;
        }

        TreeMap<Integer, CsStack.Result> full() {
            w.resetReturns();
            last = w.analyseAll(table::counts);
            return last;
        }

        public String summary() {
            long scripts = last.size(), clean = last.values().stream().filter(r -> r.violations().isEmpty() && r.complete()).count();
            return scripts + " analysed, " + clean + " complete and clean, " + violations(last) + " violations, "
                    + last.values().stream().filter(r -> !r.complete()).count() + " incomplete";
        }

        /** Score of one effect for an opcode over the scripts using it: violations * 4 + 1 per unvisited instruction / 64. */
        long score(int op, String pops, String pushes, List<Integer> scripts) {
            CsTable.Effect old = table.get(op);
            table.put(new CsTable.Effect(op, pops, pushes, "try", ""));
            try {
                TreeMap<Integer, CsStack.Result> res = new TreeMap<>();
                for (int id : scripts) res.put(id, CsStack.analyse(id, w.scripts.get(id), w, table::counts));
                long unvisited = 0;
                for (CsStack.Result r : res.values()) unvisited += r.size - r.visited;
                return weight(res) * 64 + unvisited;
            } finally {
                if (old == null) table.remove(op); else table.put(old);
            }
        }

        /**
         * Candidate pop bounds: the smallest depth per stack seen on entry to the opcode over the scripts using it,
         * found by analysing them with the opcode marked unknown (no candidate may underflow anywhere).
         */
        int[] popBounds(int op, List<Integer> scripts) {
            CsTable.Effect old = table.get(op);
            table.remove(op);
            int[] min = null;
            try {
                for (int id : scripts) {
                    Cs2.Script s = w.scripts.get(id);
                    CsStack.Result r = CsStack.analyse(id, s, w, table::counts);
                    for (var e : r.unknownAt.entrySet()) {
                        if (s.code.get(e.getKey()).op != op) continue;
                        if (min == null) min = e.getValue().clone();
                        else for (int t = 0; t < 3; t++) min[t] = Math.min(min[t], e.getValue()[t]);
                    }
                }
            } finally {
                if (old != null) table.put(old);
            }
            // no occurrence reached (other unknown opcodes in the way): generous bounds
            return min != null ? new int[]{Math.min(min[0], 10), Math.min(min[1], 5), Math.min(min[2], 3)} : new int[]{8, 4, 2};
        }

        record Best(String pops, String pushes, long score, int ties) {}

        Best learn(int op) {
            List<Integer> scripts = users.getOrDefault(op, List.of());
            if (scripts.size() > MAX_SCRIPTS) scripts = scripts.subList(0, MAX_SCRIPTS);
            int[] b = popBounds(op, scripts);
            Best best = null;
            int ties = 0;
            for (int pl = 0; pl <= b[2]; pl++) for (int ps = 0; ps <= b[1]; ps++) for (int pi = 0; pi <= b[0]; pi++) {
                for (int ql = 0; ql <= 1; ql++) for (int qs = 0; qs <= 2; qs++) for (int qi = 0; qi <= 3; qi++) {
                    if (qi + qs + ql > 3) continue;
                    String pops = CsTable.sig(new int[]{pi, ps, pl}), pushes = CsTable.sig(new int[]{qi, qs, ql});
                    long s = score(op, pops, pushes, scripts);
                    if (best == null || s < best.score) { best = new Best(pops, pushes, s, 0); ties = 0; }
                    else if (s == best.score) ties++;
                }
            }
            return new Best(best.pops, best.pushes, best.score, ties);
        }

        public List<String> run() {
            List<String> log = new ArrayList<>();
            java.util.function.Consumer<String> say = m -> { log.add(m); System.out.println(m); };
            full();
            say.accept("seed: " + summary());
            // 1. learn the opcodes the seed lacks, most frequent first, a few passes (later ops see more context)
            for (int pass = 0; pass < 4; pass++) {
                List<Integer> unknown = new ArrayList<>();
                for (int op : freq.keySet()) if (!special(op) && !table.has(op)) unknown.add(op);
                if (unknown.isEmpty()) break;
                unknown.sort(Comparator.comparing((Integer op) -> -freq.get(op)).thenComparing(op -> op));
                for (int op : unknown) {
                    Best bst = learn(op);
                    table.put(new CsTable.Effect(op, bst.pops, bst.pushes, "learned", ""));
                    say.accept(String.format("learned %5d %-8s -> %-4s (%d uses, score %d, %d ties)", op, bst.pops, bst.pushes, freq.get(op), bst.score, bst.ties));
                }
                full();
                say.accept("after learning pass " + pass + ": " + summary());
            }
            // 2. coordinate descent over every learned opcode and every opcode blamed for a violation
            for (int round = 0; round < 10; round++) {
                TreeMap<Integer, Integer> blame = new TreeMap<>();
                for (CsStack.Result r : last.values())
                    for (CsStack.Problem p : r.violations()) {
                        TreeSet<Integer> ops = new TreeSet<>();
                        for (int op : p.suspects()) if (!special(op)) ops.add(op);
                        for (int op : ops) blame.merge(op, 1, Integer::sum);
                    }
                TreeSet<Integer> cand = new TreeSet<>(blame.keySet());
                for (CsTable.Effect e : table.all().values()) if (e.source().equals("learned") && freq.containsKey(e.op())) cand.add(e.op());
                List<Integer> order = new ArrayList<>(cand);
                order.sort(Comparator.comparing((Integer op) -> -(double) blame.getOrDefault(op, 0) / freq.get(op)).thenComparing(op -> -freq.get(op)).thenComparing(op -> op));
                int improved = 0;
                for (int op : order) {
                    CsTable.Effect cur = table.get(op);
                    if (cur == null || cur.special() || cur.source().equals("manual")) continue;
                    List<Integer> scripts = users.get(op);
                    if (scripts.size() > MAX_SCRIPTS) scripts = scripts.subList(0, MAX_SCRIPTS);
                    long now = score(op, cur.pops(), cur.pushes(), scripts);
                    if (now == 0) continue;
                    Best bst = learn(op);
                    if (bst.score < now) {
                        String src = cur.source().equals("learned") ? "learned" : "relearned";
                        table.put(new CsTable.Effect(op, bst.pops, bst.pushes, src, cur.name()));
                        say.accept(String.format("round %d: %5d %s -> %s  was %s -> %s (%d blamed of %d uses, score %d -> %d)", round, op, bst.pops, bst.pushes,
                                cur.pops(), cur.pushes(), blame.getOrDefault(op, 0), freq.get(op), now, bst.score));
                        improved++;
                    }
                }
                full();
                say.accept("after round " + round + " (" + improved + " changed): " + summary());
                if (improved == 0) break;
            }
            // 3. what is left
            Map<String, Integer> kinds = new TreeMap<>();
            Map<String, List<String>> ex = new LinkedHashMap<>();
            Map<Integer, Integer> unknownOps = new TreeMap<>();
            for (CsStack.Result r : last.values()) {
                for (CsStack.Problem p : r.problems) {
                    kinds.merge(p.kind(), 1, Integer::sum);
                    List<String> l = ex.computeIfAbsent(p.kind(), k -> new ArrayList<>());
                    if (l.size() < 15) l.add("script " + r.id + " " + p);
                }
                for (int op : r.unknownOps) unknownOps.merge(op, 1, Integer::sum);
            }
            log.add("remaining problems by kind: " + kinds);
            ex.forEach((k, l) -> { log.add("  " + k + ":"); l.forEach(s -> log.add("    " + s)); });
            log.add("unknown ops: " + unknownOps);
            log.add("long type chars: " + w.types.longChars());
            Map<Integer, Integer> learnedCounts = new HashMap<>();
            for (CsTable.Effect e : table.all().values()) learnedCounts.merge(e.source().hashCode(), 1, Integer::sum);
            log.add("final: " + summary());
            return log;
        }
    }
}
