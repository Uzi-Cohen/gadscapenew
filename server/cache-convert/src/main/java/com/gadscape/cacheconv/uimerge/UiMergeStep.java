package com.gadscape.cacheconv.uimerge;

import com.gadscape.cacheconv.convert.Cs2;
import com.gadscape.cacheconv.convert.ScriptTrailer;
import com.gadscape.cacheconv.core.Arch;
import com.gadscape.cacheconv.core.Ctx;
import com.gadscape.cacheconv.core.GroupData;
import com.gadscape.cacheconv.core.Kind;
import com.gadscape.cacheconv.core.Report;
import com.gadscape.cacheconv.core.Step;

import java.nio.file.Path;
import java.util.List;
import java.util.TreeMap;

/**
 * "ui-merge": writes the three-way-merged vanilla interfaces and clientscripts (spec policy 8) from the data in
 * resources/ui-merge (generated by {@link UiMergeGen}, explained per id in NOTES.md):
 * <ul>
 *   <li>every entry was merged against a BASE group whose SHA-256 the manifest records; a BASE that differs is an
 *       error (regenerate with {@code UiMergeMain gen}) and the entry is skipped;</li>
 *   <li>interfaces: merged components replace or extend BASE's ({@code .mode merge}), or the listed components are the
 *       whole interface ({@code .mode replace}); scripts are assembled from their {@link CsText} form and read back;</li>
 *   <li>ids in GadScape's parts (component fields set from USER, script lines marked {@code u}) go through the id map,
 *       so relocations made by earlier steps (custom scripts, sprites, vars, configs, interfaces) are followed. BASE's
 *       own code is never remapped (BASE ids never move).</li>
 * </ul>
 * Run it after ui-relocate and the steps that relocate sprites, models, seqs, vars and configs; before ui-convert and
 * the reference checks. Option {@code --uimerge.data=DIR} reads the data from a directory instead of the classpath.
 */
public final class UiMergeStep implements Step {
    @Override public String name() { return "ui-merge"; }

    @Override public void run(Ctx ctx) {
        String dirOpt = ctx.opt.get("uimerge.data", null);
        Path dir = dirOpt == null ? null : Path.of(dirOpt);
        List<MergeData.Entry> manifest = MergeData.manifest(dir);
        if (manifest.isEmpty()) { ctx.report.error("ui-merge data not found (resources/ui-merge/manifest.tsv)"); return; }
        int ifs = 0, comps = 0, scripts = 0, mapped = 0, kept = 0;
        for (MergeData.Entry e : manifest) {
            boolean iface = e.kind().equals("interface");
            int arch = iface ? Arch.INTERFACES : Arch.SCRIPTS;
            Kind kind = iface ? Kind.INTERFACE : Kind.SCRIPT;
            GroupData bg = ctx.base.group(arch, e.id());
            String sha = MergeData.sha(bg);
            if (!sha.equals(e.baseSha())) {
                ctx.report.error(kind.key, e.id(), "BASE's group differs from the one the UI merge was made against (" + e.baseSha().substring(0, 12) + "): regenerate the ui-merge data; BASE's version stays");
                continue;
            }
            if (e.decision().equals("base")) {
                ctx.report.add(Report.Decision.TAKEN_FROM_BASE, kind, e.id(), e.note());
                kept++;
                continue;
            }
            String text = MergeData.text(dir, e.file());
            if (text == null) { ctx.report.error(kind.key, e.id(), "ui-merge data file " + e.file() + " missing"); continue; }
            Report.Decision d = e.decision().equals("user") ? Report.Decision.USER_CHANGED : Report.Decision.MERGED;
            if (iface) {
                MergeData.IfData data = MergeData.readIf(text);
                if (data.iface() != e.id()) { ctx.report.error(kind.key, e.id(), e.file() + " is for interface " + data.iface()); continue; }
                GroupData cur = ctx.out.group(Arch.INTERFACES, e.id());
                GroupData.Builder b = data.mode().equals("replace") || cur == null ? new GroupData.Builder(e.id()).name(cur == null ? -1 : cur.name) : cur.toBuilder();
                int[] m = {0};
                for (MergeData.IfLine l : data.comps()) {
                    IfComp c = IfComp.decode(l.bytes());
                    if (!l.refs().isEmpty()) {
                        c = IfMerge.mapRefs(c, l.refs(), (tag, v) -> { int nv = RefKinds.map(ctx.ids, tag, v); if (nv != v) m[0]++; return nv; });
                    }
                    byte[] bytes = c.encode();
                    if (!java.util.Arrays.equals(IfComp.decode(bytes).encode(), bytes)) { ctx.report.error(kind.key, e.id(), "component " + l.comp() + " does not round-trip"); continue; }
                    b.put(l.comp(), bytes);
                    comps++;
                }
                ctx.out.putGroup(Arch.INTERFACES, b.build());
                mapped += m[0];
                ctx.report.add(d, kind, e.id(), data.comps().size() + " component(s) (" + data.mode() + ")" + (m[0] > 0 ? ", " + m[0] + " relocated id(s) followed" : "") + ": " + e.note());
                ifs++;
            } else {
                CsText.Doc doc;
                try { doc = CsText.read(text); } catch (RuntimeException ex) { ctx.report.error(kind.key, e.id(), e.file() + ": " + ex.getMessage()); continue; }
                int m = 0;
                TreeMap<String, Integer> missing = new TreeMap<>();
                for (Cs2.Ins in : doc.s.code) {
                    CsText.Meta meta = doc.meta(in);
                    if (!meta.user() || meta.tag() == null || in.op == Cs2.SCONST || in.op == Cs2.LCONST) continue;
                    int nv = RefKinds.map(ctx.ids, meta.tag(), in.i);
                    if (nv != in.i) { in.i = nv; m++; }
                    if (in.op == Cs2.GOSUB && !ctx.out.hasGroup(Arch.SCRIPTS, in.i) && !ctx.user().hasGroup(Arch.SCRIPTS, ctx.ids.origin(Kind.SCRIPT, in.i) >= 0 ? ctx.ids.origin(Kind.SCRIPT, in.i) : in.i))
                        missing.merge("gosub " + in.i, 1, Integer::sum);
                }
                for (var st : doc.switchTags.entrySet()) {
                    String[] tk = st.getKey().split(":");
                    int table = Integer.parseInt(tk[0]), key = Integer.parseInt(tk[1]);
                    int nk = RefKinds.map(ctx.ids, st.getValue(), key);
                    if (nk == key) continue;
                    java.util.LinkedHashMap<Integer, Integer> old = doc.s.switches.get(table), n = new java.util.LinkedHashMap<>();
                    for (var c : old.entrySet()) n.put(c.getKey() == key ? nk : c.getKey(), c.getValue());
                    doc.s.switches.set(table, n);
                    m++;
                }
                byte[] bytes = Cs2.write241(doc.s);
                try { ScriptTrailer.verify241(e.id(), bytes); } catch (RuntimeException ex) { ctx.report.error(kind.key, e.id(), ex.getMessage()); continue; }
                for (var x : missing.entrySet()) ctx.report.warn(kind.key, e.id(), x.getKey() + ": the target is in neither the output nor USER");
                ctx.out.putGroup(Arch.SCRIPTS, GroupData.single(e.id(), bg == null ? -1 : bg.name, bytes));
                mapped += m;
                ctx.report.add(d, kind, e.id(), doc.s.code.size() + " instructions" + (m > 0 ? ", " + m + " relocated id(s) followed" : "") + ": " + e.note());
                scripts++;
            }
        }
        ctx.report.count("interfaces written", ifs);
        ctx.report.count("interface components written", comps);
        ctx.report.count("scripts written", scripts);
        ctx.report.count("kept BASE's version", kept);
        ctx.report.count("relocated ids followed", mapped);
        ctx.log("%d interfaces (%d components) and %d scripts written, %d kept from BASE, %d relocated ids followed", ifs, comps, scripts, kept, mapped);
    }
}
