package com.gadscape.cacheconv.uimerge;

import com.gadscape.cacheconv.core.Arch;
import com.gadscape.cacheconv.core.GroupData;
import com.gadscape.cacheconv.core.JagCache;
import com.gadscape.cacheconv.core.Options;
import com.gadscape.cacheconv.ui.ScriptSet;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Generates the UI merge data (resources/ui-merge) from the caches and {@link UiMergeSpecs} / {@link ScriptRecipes}:
 * the merged interfaces and scripts, manifest.tsv, component-remap.tsv and NOTES.md. Deterministic: the same inputs
 * give the same files. Run it when an input or a spec changes:
 * <pre>
 *   dev/run.sh uimerge.UiMergeMain gen [--to=DIR] [--server=SERVER_DIR]     (default DIR: the module's resources/ui-merge)
 * </pre>
 */
public final class UiMergeGen implements IfMerge.Env {
    final JagCache base, user, van;
    final IfNames names;
    final CompRemap.Table table;
    final Path serverDir;
    private ScriptSet set;
    private final TreeMap<Integer, TreeMap<Integer, CompRemap.Row>> remaps = new TreeMap<>();
    private final TreeMap<Integer, Integer> userCounts = new TreeMap<>();
    final TreeMap<Integer, IfMerge.Result> ifResults = new TreeMap<>();
    final TreeMap<Integer, UiMergeSpecs.IfSpec> ifSpecs = UiMergeSpecs.interfaces();
    final List<String> manifest = new ArrayList<>();
    final TreeMap<String, String> files = new TreeMap<>();
    final StringBuilder notesIf = new StringBuilder(), notesCs = new StringBuilder();
    final List<String> problems = new ArrayList<>();

    public UiMergeGen(JagCache base, JagCache user, JagCache van, Path tablePath, Path serverDir) {
        this.base = base; this.user = user; this.van = van;
        this.names = IfNames.of(base);
        this.table = CompRemap.loadTable(tablePath);
        this.serverDir = serverDir;
    }

    // ------------------------------------------------------------------ Env

    /** USER scripts analysed together (argument types of hook scripts); computed once. */
    synchronized ScriptSet scripts() {
        if (set == null) { set = new ScriptSet(user); set.analyseAll(); }
        return set;
    }

    @Override public String[] argTypes(int script) { return scripts().argTypes(script); }

    @Override public boolean looksLikeComponent(int v) {
        if (v <= 0 || (v <= Integer.MIN_VALUE + 64)) return false;
        int g = v >>> 16, c = v & 0xffff;
        if (g == 0) return false;
        int n = userCounts.computeIfAbsent(g, k -> { int[] f = user.fileIds(Arch.INTERFACES, k); return f.length == 0 ? 0 : f[f.length - 1] + 1; });
        return c < n;
    }

    @Override public int otherComponent(int packed) {
        int g = packed >>> 16, c = packed & 0xffff;
        if (!van.hasGroup(Arch.INTERFACES, g) || !base.hasGroup(Arch.INTERFACES, g)) return packed;   // custom (or gone): ids follow ctx.ids at build time
        IfMerge.Result merged = ifResults.get(g);
        if (merged != null) { Integer to = merged.userToMerged.get(c); return to == null || to < 0 ? packed : (g << 16) | to; }
        CompRemap.Row r = remap(g).get(c);
        if (r == null || r.c241() < 0) { problems.add("component " + g + ":" + c + " (in a GadScape edit) has no 241 counterpart: kept"); return packed; }
        return (g << 16) | r.c241();
    }

    TreeMap<Integer, CompRemap.Row> remap(int g) {
        return remaps.computeIfAbsent(g, k -> {
            TreeMap<Integer, CompRemap.Row> r = CompRemap.build(k, table, names, CompRemap.comps211(van.group(Arch.INTERFACES, k)), CompRemap.comps241(base.group(Arch.INTERFACES, k)));
            if (k == SpellAnchors.SPELLBOOK) {
                TreeMap<Integer, Integer> a = SpellAnchors.anchors(van, base);
                for (var e : a.entrySet()) {
                    CompRemap.Row old = r.get(e.getKey());
                    if (old != null && old.c241() == e.getValue()) continue;
                    r.put(e.getKey(), new CompRemap.Row(e.getKey(), e.getValue(), "high", "spell obj anchor (param 596; table said " + (old == null ? "nothing" : old.c241()) + ")"));
                }
            }
            return r;
        });
    }

    /** Everything: merged interfaces and scripts, the component remap, manifest and notes (into {@link #files}). */
    public void run() throws IOException {
        interfaces();
        ScriptRecipes.run(this);
        checkCalls();
        files.put("component-remap.tsv", componentRemapTsv());
        StringBuilder m = new StringBuilder("# kind\tid\tdecision\tdata\tbase_sha256\tnote (generated by UiMergeGen; see NOTES.md)\n");
        for (String l : manifest) m.append(l).append('\n');
        files.put("manifest.tsv", m.toString());
        files.put("NOTES.md", UiMergeNotes.render(this));
    }

    // ------------------------------------------------------------------ interfaces

    void interfaces() {
        for (UiMergeSpecs.IfSpec s : ifSpecs.values()) {
            int g = s.id();
            GroupData gb = base.group(Arch.INTERFACES, g), gu = user.group(Arch.INTERFACES, g), gv = van.group(Arch.INTERFACES, g);
            String sha = MergeData.sha(gb);
            StringBuilder n = notesIf;
            n.append("\n### Interface ").append(g).append(" (").append(names.name(g)).append(")\n\n");
            n.append("VAN211 ").append(gv.fileCount()).append(", USER ").append(gu.fileCount()).append(", BASE ").append(gb.fileCount()).append(" components. ");
            n.append("**").append(s.decision().name().toLowerCase()).append("**: ").append(s.reason()).append(".\n");
            for (String w : UiMergeSpecs.notesFor(s)) n.append("\n- ").append(w).append('\n');
            switch (s.decision()) {
                case BASE -> manifest.add(String.join("\t", "interface", "" + g, "base", "-", sha, s.reason()));
                case USER -> {
                    if (!CompRemap.unchanged(van, base, g)) problems.add("interface " + g + ": decision USER but BASE changed it since 211");
                    TreeMap<Integer, IfComp> u = CompRemap.comps211(gu);
                    IfMerge.Result r = new IfMerge.Result(g);
                    for (var e : u.entrySet()) {
                        IfComp c = IfMerge.toMerged(g, e.getValue(), x -> x, x -> x, this, true);
                        IfMerge.Comp mc = new IfMerge.Comp(e.getKey(), c, "user");
                        mc.refs.addAll(IfMerge.allRefs(c, this));
                        r.comps.put(e.getKey(), mc);
                        r.userToMerged.put(e.getKey(), e.getKey());
                    }
                    ifResults.put(g, r);
                    String file = "interfaces/" + g + ".if";
                    files.put(file, MergeData.writeIf("interface " + g + ": USER's version (see NOTES.md); generated by UiMergeGen", g, "replace", r.comps));
                    manifest.add(String.join("\t", "interface", "" + g, "user", file, sha, s.reason()));
                    n.append("\nAll ").append(u.size()).append(" USER components are written (relocatable references follow the id map).\n");
                }
                case MERGE -> {
                    TreeMap<Integer, IfComp> v = CompRemap.comps211(gv), u = CompRemap.comps211(gu), b = CompRemap.comps241(gb);
                    TreeMap<Integer, CompRemap.Row> rm = new TreeMap<>(remap(g));
                    if (s.remapOverride() != null) for (var e : s.remapOverride().entrySet()) rm.put(e.getKey(), new CompRemap.Row(e.getKey(), e.getValue(), "high", "ui-merge override"));
                    if (s.retarget() != null) for (var e : s.retarget().entrySet()) rm.put(e.getKey(), new CompRemap.Row(e.getKey(), e.getValue(), "high", "ui-merge retarget"));
                    IfMerge.Result r = IfMerge.merge(g, v, u, b, rm, s.options(), this);
                    ifResults.put(g, r);
                    String file = "interfaces/" + g + ".if";
                    files.put(file, MergeData.writeIf("interface " + g + ": BASE 2746 + GadScape's edits (see NOTES.md); generated by UiMergeGen", g, "merge", r.comps));
                    manifest.add(String.join("\t", "interface", "" + g, "merged", file, sha, s.reason()));
                    list(n, "Re-applied", r.applied);
                    list(n, "Added", r.added);
                    list(n, "Conflicts", r.conflicts);
                    list(n, "Not re-applied", r.skipped);
                    for (IfMerge.Comp c : r.comps.values()) if (c.origin.equals("added") && c.c.if3 && c.c.i("parent") < 0)
                        problems.add("interface " + g + ": added component " + c.id + " has no parent in BASE");
                }
            }
        }
    }

    /**
     * GadScape's calls into vanilla scripts (gosubs in its script lines, hook scripts in its component fields) must find
     * the same signature in BASE: same name hash as VAN211 and the same int/object arguments (no long ones); otherwise
     * the call would need an adapter.
     */
    void checkCalls() {
        TreeMap<Integer, TreeSet<String>> calls = new TreeMap<>();
        for (var f : files.entrySet()) {
            if (f.getKey().startsWith("scripts/")) {
                CsText.Doc d = CsText.read(f.getValue());
                for (var in : d.s.code) if (in.op == 40 && d.meta(in).user()) calls.computeIfAbsent(in.i, k -> new TreeSet<>()).add("script " + d.id);
                // an untyped GadScape constant shaped like a vanilla component that moved in 241 would keep its 211 number
                for (var in : d.s.code) {
                    CsText.Meta m = d.meta(in);
                    if (in.op != 0 || !m.user() || m.tag() != null || !looksLikeComponent(in.i)) continue;
                    int g = in.i >>> 16;
                    if (!van.hasGroup(Arch.INTERFACES, g) || !base.hasGroup(Arch.INTERFACES, g)) continue;
                    int to = otherComponent(in.i);
                    if (to != in.i) problems.add("script " + d.id + ": untyped constant " + in.i + " looks like component " + g + ":" + (in.i & 0xffff) + ", which is " + (to >>> 16) + ":" + (to & 0xffff) + " in 241 (not rewritten; check by hand)");
                }
            } else if (f.getKey().startsWith("interfaces/")) {
                MergeData.IfData d = MergeData.readIf(f.getValue());
                for (MergeData.IfLine l : d.comps()) for (String r : l.refs()) if (r.endsWith("#0:script")) {
                    IfComp c = IfComp.decode(l.bytes());
                    List<Object> a = c.list(r.substring(0, r.indexOf('#')));
                    if (a != null && !a.isEmpty() && a.get(0) instanceof Integer t) calls.computeIfAbsent(t, k -> new TreeSet<>()).add("interface " + d.iface() + ":" + l.comp() + " (hook)");
                }
            }
        }
        for (var e : calls.entrySet()) {
            int t = e.getKey();
            byte[] v = van.single(Arch.SCRIPTS, t), u = user.single(Arch.SCRIPTS, t), b = base.single(Arch.SCRIPTS, t);
            if (v == null) continue;                      // GadScape's own script: converted (and maybe relocated) by ui-convert
            String where = String.join(", ", e.getValue());
            if (b == null) { problems.add("vanilla script " + t + " called by " + where + " is gone in 241"); continue; }
            if (van.groupName(Arch.SCRIPTS, t) != base.groupName(Arch.SCRIPTS, t)) { problems.add("vanilla script " + t + " called by " + where + " is a different script in 241 (name hash)"); continue; }
            int[] a = com.gadscape.cacheconv.convert.ScriptTrailer.args211(u != null ? u : v), c = com.gadscape.cacheconv.convert.ScriptTrailer.args241WithLongs(b);
            if (a[0] != c[0] || a[1] != c[1] || c[2] != 0)
                problems.add("vanilla script " + t + " called by " + where + " takes " + c[0] + "/" + c[1] + "/" + c[2] + " args in 241, " + a[0] + "/" + a[1] + " in 211");
        }
    }

    static void list(StringBuilder n, String title, List<String> items) {
        if (items.isEmpty()) return;
        n.append("\n").append(title).append(":\n");
        for (String i : items) n.append("- ").append(i).append('\n');
    }

    // ------------------------------------------------------------------ component remap TSV

    /** The 211 -> 241 component table for every vanilla interface the server references (plus the table's and the merged ones). */
    String componentRemapTsv() throws IOException {
        TreeSet<Integer> ifaces = new TreeSet<>(table.rows.keySet());
        // the scan needs the server sources; without them (tests, another checkout) the list stored by the last generation is used
        TreeSet<Integer> scanned = serverDir != null ? ServerScan.interfaces(serverDir) : storedServerInterfaces();
        files.put("server-interfaces.txt", "# vanilla and custom interface ids the GadScape server code references (ServerScan), used for component-remap.tsv\n" + compact(scanned) + "\n");
        ifaces.addAll(scanned);
        for (int g : UiMergeSpecs.INTERFACES) ifaces.add(g);
        StringBuilder sb = new StringBuilder();
        sb.append("# GadScape 211 -> build 241 (openrs2 2746) component remap, generated by gadconv UiMergeGen (ui-merge area).\n");
        sb.append("# component211 is the id in GadScape's own 211 cache (USER), the numbering the server code uses; it equals vanilla 211\n");
        sb.append("# except in the interfaces the user changed. component241 is the id in the built cache (BASE numbering; components\n");
        sb.append("# GadScape added are appended after BASE's last one). -1 = no 241 counterpart.\n");
        sb.append("# Sources (notes column): the server docs table (docs/rev241/interface-remap.tsv, checked against BASE's component\n");
        sb.append("# names in gamevals), the UI merge (merged/added/user), or content alignment for interfaces the docs table lacks.\n");
        sb.append("# Interfaces the server references (server-interfaces.txt): ").append(compact(scanned)).append('\n');
        sb.append("# interface\tname241\tcomponent211\tcomponent241\tconfidence\tname241\tnotes\n");
        for (int g : ifaces) {
            if (!van.hasGroup(Arch.INTERFACES, g) || !base.hasGroup(Arch.INTERFACES, g)) continue;   // custom or gone: not a vanilla remap
            String in = names.name(g) == null ? "" : names.name(g);
            UiMergeSpecs.IfSpec s = ifSpecs.get(g);
            IfMerge.Result r = ifResults.get(g);
            if (UiMergeSpecs.REUSED_IDS.containsKey(g)) {
                if (names.has(g) && !UiMergeSpecs.REUSED_IDS.get(g).contains(" " + in + ";"))
                    problems.add("interface " + g + ": REUSED_IDS names another 241 interface than BASE's gamevals (" + in + ")");
                for (int c : user.fileIds(Arch.INTERFACES, g)) sb.append(row(g, in, c, -1, "none", "", "ui-merge: " + UiMergeSpecs.REUSED_IDS.get(g)));
                continue;
            }
            if (s != null && s.decision() == UiMergeSpecs.Decision.BASE && s.remapOverride() != null) {
                TreeMap<Integer, String[]> t = table.rows.get(g);
                TreeMap<Integer, CompRemap.Row> rm = remap(g);
                for (int c : van.fileIds(Arch.INTERFACES, g)) {
                    Integer ov = s.remapOverride().get(c);
                    if (ov != null) { sb.append(row(g, in, c, ov, ov < 0 ? "none" : "high", ov < 0 ? "" : names.comp(g, ov), "ui-merge override (by role)")); continue; }
                    String[] f = t == null ? null : t.get(c);
                    if (f != null) { sb.append(String.join("\t", f)).append('\n'); continue; }
                    CompRemap.Row row = rm.get(c);
                    int to = row == null ? -1 : row.c241();
                    sb.append(row(g, in, c, to, row == null ? "low" : row.confidence(), to < 0 ? "" : String.valueOf(names.comp(g, to)), row == null ? "" : row.method()));
                }
                continue;
            }
            if (r != null) {
                TreeMap<Integer, CompRemap.Row> rm = remap(g);
                for (var e : r.userToMerged.entrySet()) {
                    int c = e.getKey(), to = e.getValue();
                    String how;
                    String conf;
                    if (s.decision() == UiMergeSpecs.Decision.USER) { how = "ui-merge: USER's interface"; conf = "high"; }
                    else if (!r.userToVan.containsKey(c)) { how = "ui-merge: GadScape component appended"; conf = "high"; }
                    else {
                        int v = r.userToVan.get(c);
                        Integer ov = s.remapOverride() == null ? null : s.remapOverride().get(v);
                        CompRemap.Row vr = rm.get(v);
                        to = ov != null ? ov : vr == null ? -1 : vr.c241();
                        conf = ov != null ? (ov < 0 ? "none" : "high") : vr == null ? "low" : vr.confidence();
                        how = (ov != null ? "ui-merge override" : vr == null ? "?" : vr.method()) + (v != c ? " (USER " + c + " = 211 " + v + ")" : "");
                    }
                    String cn = to < 0 ? "" : names.comp(g, to) != null ? names.comp(g, to) : "gadscape_" + c;
                    sb.append(row(g, in, c, to, conf, cn, how));
                }
                continue;
            }
            TreeMap<Integer, String[]> t = table.rows.get(g);
            TreeMap<Integer, CompRemap.Row> rm = remap(g);
            for (int c : van.fileIds(Arch.INTERFACES, g)) {
                String[] f = t == null ? null : t.get(c);
                if (f != null) { sb.append(String.join("\t", f)).append('\n'); continue; }
                CompRemap.Row row = rm.get(c);
                int to = row == null ? -1 : row.c241();
                sb.append(row(g, in, c, to, row == null ? "low" : row.confidence(), to < 0 ? "" : String.valueOf(names.comp(g, to)), row == null ? "" : row.method()));
            }
        }
        return sb.toString();
    }

    static TreeSet<Integer> storedServerInterfaces() {
        TreeSet<Integer> r = new TreeSet<>();
        String t = MergeData.text(null, "server-interfaces.txt");
        if (t == null) return r;
        for (String l : t.split("\n")) {
            if (l.isBlank() || l.startsWith("#")) continue;
            for (String part : l.trim().split(",")) {
                int dash = part.indexOf('-');
                if (dash > 0) for (int i = Integer.parseInt(part.substring(0, dash)); i <= Integer.parseInt(part.substring(dash + 1)); i++) r.add(i);
                else r.add(Integer.parseInt(part));
            }
        }
        return r;
    }

    private static String row(int g, String in, int c, int to, String conf, String cn, String notes) {
        return g + "\t" + in + "\t" + c + "\t" + to + "\t" + conf + "\t" + (cn == null ? "" : cn) + "\t" + notes + "\n";
    }

    static String compact(TreeSet<Integer> s) {
        StringBuilder sb = new StringBuilder();
        Integer lo = null, prev = null;
        for (int v : s) {
            if (lo == null) { lo = v; prev = v; continue; }
            if (v == prev + 1) { prev = v; continue; }
            sb.append(sb.length() == 0 ? "" : ",").append(lo.equals(prev) ? "" + lo : lo + "-" + prev);
            lo = v; prev = v;
        }
        if (lo != null) sb.append(sb.length() == 0 ? "" : ",").append(lo.equals(prev) ? "" + lo : lo + "-" + prev);
        return sb.toString();
    }

    // ------------------------------------------------------------------ output

    /** Writes every generated file under {@code to} (only files that changed are rewritten). */
    void write(Path to) throws IOException {
        Files.createDirectories(to);
        for (var e : files.entrySet()) {
            Path p = to.resolve(e.getKey());
            Files.createDirectories(p.getParent());
            byte[] b = e.getValue().getBytes(StandardCharsets.UTF_8);
            if (Files.isRegularFile(p) && java.util.Arrays.equals(Files.readAllBytes(p), b)) continue;
            Files.write(p, b);
        }
    }
}
